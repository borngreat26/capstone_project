"""Check every file Git would publish for private data. Exits with an error if anything looks wrong.

Usage:  python scripts/check_public_files.py
It reviews tracked files plus untracked files that .gitignore does not exclude.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from src.utils import REPO_ROOT

MAX_FILE_MB = 10
PRIVATE_NAME = re.compile(r'tiffany|23andme|^genome_.*\.txt$|\.(vcf|bcf|tbi|csi|sscore|traw|pgen|pvar|psam|vcor|afreq)(\.gz)?$', re.I)
GENOTYPE_FILE = re.compile(r'\.(bed|bim|fam)$')
TEXT_FILE = re.compile(r'\.(py|md|ipynb|yml|yaml|txt|tsv|gitignore)$|^\.gitignore$')
BLOCKED_TEXT = ['AmariutaBartell', '/Users/', '/opt/homebrew', '/private/tmp', 'This data file generated by 23andMe']
PUBLIC_NOTEBOOKS = ['notebooks/weekly_tasks_public.ipynb', 'notebooks/quarter1_project.ipynb']


def files_to_publish():
    listed = subprocess.run(['git', 'ls-files', '-co', '--exclude-standard'], cwd=REPO_ROOT, capture_output=True,
                            text=True, check=True).stdout.splitlines()
    return [name for name in listed if (REPO_ROOT / name).is_file()]


def private_result_values():
    """Personal results, read from the local summary if it exists, so they are never written in this script."""
    summary_path = REPO_ROOT / 'data/week5_results/height_prs_summary.tsv'
    if not summary_path.exists():
        return []
    summary = pd.read_csv(summary_path, sep='\t', index_col=0)['Value']
    values = []
    for key, digits in [('Tiffany PRS', 5), ('Tiffany percentile', 2), ('Tiffany z-score', 3)]:
        values.append(f"{summary[key]:.{digits}f}")
    return values


def readable_text(path):
    """A notebook's text without its embedded images; other files as they are."""
    text = path.read_text(errors='ignore')
    if path.suffix == '.ipynb':
        notebook = json.loads(text)
        for cell in notebook['cells']:
            cell['metadata'] = {}  # Execution timestamps can match result values by chance.
            for output in cell.get('outputs', []):
                output.get('data', {}).pop('image/png', None)
        text = json.dumps(notebook, ensure_ascii=False)
    return text


def private_counts():
    """Counts that describe the private genotype file, read from local results so they are never written here."""
    counts = []
    summary_path = REPO_ROOT / 'data/week5_results/height_prs_summary.tsv'
    if summary_path.exists():
        counts.append(int(pd.read_csv(summary_path, sep='\t', index_col=0)['Value']['Shared scoring SNPs']))
    calls_path = REPO_ROOT / 'data/week5_results/Tiffany_converted.bim'
    if calls_path.exists():
        with calls_path.open() as handle:
            counts.append(sum(1 for _ in handle))
    return [text for count in counts for text in (str(count), f'{count:,}')]


def week_5_problems(name):
    """Week 5 cells must have no outputs or personal counts, and no output anywhere may mention the private individual."""
    problems, in_week_5 = [], False
    counts = private_counts()
    for cell in json.loads((REPO_ROOT / name).read_text())['cells']:
        source = ''.join(cell['source'])
        if cell['cell_type'] == 'markdown' and source.startswith('# Week'):
            in_week_5 = source.startswith('# Week 5')
        outputs = cell.get('outputs', [])
        if in_week_5 and outputs:
            problems.append(f'{name}: a Week 5 cell still has outputs')
        if in_week_5 and any(count in source for count in counts):
            problems.append(f'{name}: Week 5 text or code contains a private count')
        if 'tiffany' in json.dumps(outputs).lower():
            problems.append(f'{name}: an output mentions the private individual')
    return problems


def local_email():
    """The author's Git email, read at run time so that it is not written in this script."""
    email = subprocess.run(['git', 'config', 'user.email'], cwd=REPO_ROOT, capture_output=True, text=True).stdout.strip()
    return [email] if email else []


def find_problems():
    problems = []
    names = files_to_publish()
    blocked_text = BLOCKED_TEXT + local_email()
    private_values = private_result_values()
    for name in names:
        path = REPO_ROOT / name
        if PRIVATE_NAME.search(Path(name).name):
            problems.append(f'{name}: the file name looks private')
        if GENOTYPE_FILE.search(name) and not name.startswith('data/demo/'):
            problems.append(f'{name}: genotype files are only allowed in data/demo/')
        if name.startswith('data/') and not name.startswith('data/demo/'):
            problems.append(f'{name}: only data/demo/ may be published from data/')
        if path.stat().st_size > MAX_FILE_MB * 1024 * 1024:
            problems.append(f'{name}: larger than {MAX_FILE_MB} MB')
        if TEXT_FILE.search(Path(name).name) and name != 'scripts/check_public_files.py':
            text = readable_text(path)
            problems += [f'{name}: contains "{blocked}"' for blocked in blocked_text if blocked in text]
            if path.suffix in ('.ipynb', '.md', '.py'):
                problems += [f'{name}: contains a private result value' for value in private_values if value in text]
    for name in PUBLIC_NOTEBOOKS:
        if name in names:
            problems += week_5_problems(name)
    panel_fam = REPO_ROOT / 'data/LDREF/1000G.EUR.22.fam'
    if panel_fam.exists():
        panel = set(pd.read_csv(panel_fam, sep=r'\s+', header=None, dtype=str)[1])
        for name in names:
            if name.startswith('data/demo/') and name.endswith('.fam'):
                people = set(pd.read_csv(REPO_ROOT / name, sep=r'\s+', header=None, dtype=str)[1])
                if not people <= panel:
                    problems.append(f'{name}: includes someone outside the public 1000 Genomes panel')
    return names, problems


if __name__ == '__main__':
    names, problems = find_problems()
    print(f'Reviewed {len(names)} files that Git would publish.')
    for problem in problems:
        print('PROBLEM:', problem)
    print('No private-data problems found.' if not problems else f'{len(problems)} problem(s) found.')
    sys.exit(1 if problems else 0)
